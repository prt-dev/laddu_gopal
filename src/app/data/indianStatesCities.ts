export const ALL_INDIAN_STATES = INDIAN_STATES_AND_CITIES.map((s) => s.state);

export function getCitiesForState(stateName: string): string[] {
  if (!stateName) return [];
  const normalized = stateName.trim().toLowerCase();
  const matched = INDIAN_STATES_AND_CITIES.find(
    (s) => s.state.toLowerCase() === normalized
  );
  return matched ? matched.cities : [];
}
